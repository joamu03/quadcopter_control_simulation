"""
Cascade Proportional-Integral-Derivative (PID) Flight Controller for a 6-DOF Quadcopter.

Implements a two-loop hierarchical control architecture:
1. Outer Loop (3D Translational Position and Linear Velocity Control):
   - Independent PID channels for the horizontal plane (X, Y) and vertical altitude (Z).
   - Computes desired translational accelerations and maps them into the collective thrust U1
     (with gravity and tilt compensation) and reference attitude angles (phi_ref, theta_ref).
2. Inner Loop (Attitude and Angular Rate Control):
   - High-bandwidth PID control for Roll (phi), Pitch (theta), and Yaw (psi).
   - Scales commanded angular accelerations by the principal inertia tensor J = diag(Ixx, Iyy, Izz)
     to produce the control moments [tau_phi, tau_theta, tau_psi].
"""

from __future__ import annotations

import copy
from typing import Any
import numpy as np

import config


class PIDController:
    """
    Cascade PID flight controller featuring real-time hot-tuning and integral anti-windup clamping.
    """

    def __init__(
        self,
        gains: dict[str, dict[str, float]] | None = None,
    ) -> None:
        self.mass: float = float(config.MASS)
        self.gravity: float = float(config.GRAVITY)
        self.ixx: float = float(config.INERTIA_X)
        self.iyy: float = float(config.INERTIA_Y)
        self.izz: float = float(config.INERTIA_Z)
        self.max_tilt: float = float(config.MAX_TILT_ANGLE_RAD)

        self.gains: dict[str, dict[str, float]] = (
            copy.deepcopy(config.PID_GAINS) if gains is None else copy.deepcopy(gains)
        )

        # Anti-windup integral clamping bounds
        self.int_pos_limit: float = 3.0
        self.int_att_limit: float = 0.8

        # Integral error accumulators
        self.integral_pos_error: np.ndarray = np.zeros(3, dtype=float)
        self.integral_att_error: np.ndarray = np.zeros(3, dtype=float)

        # Latest attitude references generated by the outer loop [phi_ref, theta_ref, psi_ref]
        self.last_attitude_ref: np.ndarray = np.zeros(3, dtype=float)

    def reset(self) -> None:
        """Clears the accumulated integral error states of both outer and inner PID loops."""
        self.integral_pos_error[:] = 0.0
        self.integral_att_error[:] = 0.0
        self.last_attitude_ref[:] = 0.0

    # Convenience properties for GUI hot-tuning sliders
    @property
    def kp_pos_xy(self) -> float:
        return float(self.gains["pos_xy"]["kp"])

    @property
    def ki_pos_xy(self) -> float:
        return float(self.gains["pos_xy"]["ki"])

    @property
    def kd_pos_xy(self) -> float:
        return float(self.gains["pos_xy"]["kd"])

    @property
    def kp_pos_z(self) -> float:
        return float(self.gains["pos_z"]["kp"])

    @property
    def ki_pos_z(self) -> float:
        return float(self.gains["pos_z"]["ki"])

    @property
    def kd_pos_z(self) -> float:
        return float(self.gains["pos_z"]["kd"])

    @property
    def kp_att(self) -> float:
        return float(self.gains["att_roll_pitch"]["kp"])

    @property
    def ki_att(self) -> float:
        return float(self.gains["att_roll_pitch"]["ki"])

    @property
    def kd_att(self) -> float:
        return float(self.gains["att_roll_pitch"]["kd"])

    @property
    def kp_yaw(self) -> float:
        return float(self.gains["att_yaw"]["kp"])

    @property
    def kd_yaw(self) -> float:
        return float(self.gains["att_yaw"]["kd"])

    def update_gains(
        self,
        pos_xy: dict[str, float] | None = None,
        pos_z: dict[str, float] | None = None,
        att_roll_pitch: dict[str, float] | None = None,
        att_yaw: dict[str, float] | None = None,
    ) -> None:
        """
        Dynamically updates the dictionary of PID sub-loop gains in real time.
        """
        for key, new_vals in (
            ("pos_xy", pos_xy),
            ("pos_z", pos_z),
            ("att_roll_pitch", att_roll_pitch),
            ("att_yaw", att_yaw),
        ):
            if new_vals is not None and key in self.gains:
                for g_name in ("kp", "ki", "kd"):
                    if g_name in new_vals:
                        self.gains[key][g_name] = max(0.0, float(new_vals[g_name]))

    def set_gains(self, **kwargs: Any) -> None:
        """
        Updates individual scalar gains in real time from GUI slider callbacks.
        """
        if "kp_pos_xy" in kwargs:
            self.gains["pos_xy"]["kp"] = max(0.0, float(kwargs["kp_pos_xy"]))
        if "ki_pos_xy" in kwargs:
            self.gains["pos_xy"]["ki"] = max(0.0, float(kwargs["ki_pos_xy"]))
        if "kd_pos_xy" in kwargs:
            self.gains["pos_xy"]["kd"] = max(0.0, float(kwargs["kd_pos_xy"]))

        if "kp_pos_z" in kwargs:
            self.gains["pos_z"]["kp"] = max(0.0, float(kwargs["kp_pos_z"]))
        if "ki_pos_z" in kwargs:
            self.gains["pos_z"]["ki"] = max(0.0, float(kwargs["ki_pos_z"]))
        if "kd_pos_z" in kwargs:
            self.gains["pos_z"]["kd"] = max(0.0, float(kwargs["kd_pos_z"]))

        if "kp_att" in kwargs:
            self.gains["att_roll_pitch"]["kp"] = max(0.0, float(kwargs["kp_att"]))
        if "ki_att" in kwargs:
            self.gains["att_roll_pitch"]["ki"] = max(0.0, float(kwargs["ki_att"]))
        if "kd_att" in kwargs:
            self.gains["att_roll_pitch"]["kd"] = max(0.0, float(kwargs["kd_att"]))

        if "kp_yaw" in kwargs:
            self.gains["att_yaw"]["kp"] = max(0.0, float(kwargs["kp_yaw"]))
        if "kd_yaw" in kwargs:
            self.gains["att_yaw"]["kd"] = max(0.0, float(kwargs["kd_yaw"]))

    def compute_control(
        self,
        state: np.ndarray,
        setpoint_pos: np.ndarray,
        setpoint_yaw: float = 0.0,
        dt: float = config.DT,
    ) -> np.ndarray:
        """
        Computes the generalized control wrench `u = [U1, tau_phi, tau_theta, tau_psi]^T`.

        Parameters
        ----------
        state : np.ndarray (12,)
            Current state vector `[x, y, z, vx, vy, vz, phi, theta, psi, p, q, r]`.
        setpoint_pos : np.ndarray (3,)
            Desired 3D position reference `[x_ref, y_ref, z_ref]` in meters.
        setpoint_yaw : float
            Desired heading angle `psi_ref` in radians.
        dt : float
            Integration sampling period in seconds.

        Returns
        -------
        np.ndarray (4,)
            Generalized control wrench `[U1 (N), tau_phi (N*m), tau_theta (N*m), tau_psi (N*m)]`.
        """
        pos = state[0:3]
        vel = state[3:6]
        phi, theta, psi = float(state[6]), float(state[7]), float(state[8])
        p_rate, q_rate, r_rate = float(state[9]), float(state[10]), float(state[11])

        # =====================================================================
        # 1. OUTER LOOP: 3D Translational Position Control (XY and Altitude Z)
        # =====================================================================
        pos_error = np.asarray(setpoint_pos, dtype=float) - pos
        vel_error = -vel

        if dt > 0.0:
            self.integral_pos_error += pos_error * dt
            self.integral_pos_error = np.clip(
                self.integral_pos_error, -self.int_pos_limit, self.int_pos_limit
            )

        g_xy = self.gains["pos_xy"]
        g_z = self.gains["pos_z"]

        xy_scale = 3.8
        z_scale = 3.2

        ax_des = xy_scale * (
            g_xy["kp"] * pos_error[0]
            + (g_xy["ki"] + 0.25) * self.integral_pos_error[0]
            + g_xy["kd"] * vel_error[0]
        )
        ay_des = xy_scale * (
            g_xy["kp"] * pos_error[1]
            + (g_xy["ki"] + 0.25) * self.integral_pos_error[1]
            + g_xy["kd"] * vel_error[1]
        )
        az_des = z_scale * (
            g_z["kp"] * pos_error[2]
            + g_z["ki"] * self.integral_pos_error[2]
            + g_z["kd"] * vel_error[2]
        )

        ax_des = float(np.clip(ax_des, -6.5, 6.5))
        ay_des = float(np.clip(ay_des, -6.5, 6.5))
        az_des = float(np.clip(az_des, -5.5, 8.5))

        # Collective thrust U1 with gravitational feedforward and tilt projection compensation
        tilt_comp = max(float(np.cos(phi) * np.cos(theta)), 0.55)
        u1 = self.mass * (self.gravity + az_des) / tilt_comp
        u1 = float(
            np.clip(
                u1,
                4.0 * config.MIN_THRUST_PER_MOTOR,
                4.0 * config.MAX_THRUST_PER_MOTOR,
            )
        )

        # Rotate desired horizontal accelerations into the heading-aligned frame (yaw psi)
        c_psi, s_psi = np.cos(psi), np.sin(psi)
        ax_psi = ax_des * c_psi + ay_des * s_psi
        ay_psi = -ax_des * s_psi + ay_des * c_psi

        # Map desired horizontal accelerations into attitude angle references
        theta_ref = float(np.clip(np.arctan2(ax_psi, self.gravity), -self.max_tilt, self.max_tilt))
        phi_ref = float(np.clip(np.arctan2(-ay_psi, self.gravity), -self.max_tilt, self.max_tilt))
        psi_ref = float(setpoint_yaw)
        self.last_attitude_ref[:] = [phi_ref, theta_ref, psi_ref]

        # =====================================================================
        # 2. INNER LOOP: Attitude and Angular Velocity Control (Roll, Pitch, Yaw)
        # =====================================================================
        yaw_error = float((psi_ref - psi + np.pi) % (2.0 * np.pi) - np.pi)
        att_error = np.array([phi_ref - phi, theta_ref - theta, yaw_error], dtype=float)

        if dt > 0.0:
            self.integral_att_error += att_error * dt
            self.integral_att_error = np.clip(
                self.integral_att_error, -self.int_att_limit, self.int_att_limit
            )

        g_rp = self.gains["att_roll_pitch"]
        g_yaw = self.gains["att_yaw"]

        # Scale commanded angular acceleration by principal inertia moments (tau = I * alpha_des)
        att_scale = 20.0
        alpha_phi = att_scale * (
            g_rp["kp"] * att_error[0]
            + g_rp["ki"] * self.integral_att_error[0]
            - 0.35 * g_rp["kd"] * p_rate
        )
        alpha_theta = att_scale * (
            g_rp["kp"] * att_error[1]
            + g_rp["ki"] * self.integral_att_error[1]
            - 0.35 * g_rp["kd"] * q_rate
        )
        alpha_psi = att_scale * (
            g_yaw["kp"] * att_error[2]
            + g_yaw["ki"] * self.integral_att_error[2]
            - 0.45 * g_yaw["kd"] * r_rate
        )

        tau_phi = float(np.clip(self.ixx * alpha_phi, -1.6, 1.6))
        tau_theta = float(np.clip(self.iyy * alpha_theta, -1.6, 1.6))
        tau_psi = float(np.clip(self.izz * alpha_psi, -0.5, 0.5))

        return np.array([u1, tau_phi, tau_theta, tau_psi], dtype=float)
